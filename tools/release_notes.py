"""Build auditable, per-release implementation notes from reviewed PR descriptions.

Generic packaging text is not a changelog. A publish must identify actual
features/fixes and their source, so that both desktop and Android can show what
the user will receive before an update is installed.
"""
import json
import os
from pathlib import Path
import re
import subprocess


SKIP_HEADING = re.compile(r"^(?:validation|testing|tests|ci|checklist|release type|how tested|generated by)", re.I)


def implementations(pr_body):
    """Return readable PR feature bullets, excluding CI chatter and empty sections."""
    entries = []
    section = "Changes"
    excluded = False
    for raw in (pr_body or "").splitlines():
        line = raw.strip()
        match = re.match(r"^#{2,4}\s+(.+)$", line)
        if match:
            section = match[1].strip()
            excluded = bool(SKIP_HEADING.match(section))
            continue
        if excluded or len(line) < 25:
            continue
        if line.startswith("- ") and not line.startswith("- ["):
            entries.append((section, line[2:].strip()))
        elif line.startswith("|") and re.match(r"^\|\s*[1-9][0-9]*\s*\|", line):
            parts = [p.strip() for p in line.strip("|").split("|")]
            if len(parts) >= 3:
                entries.append((section, f"**{parts[1]}:** {parts[2]}"))
    return list(dict.fromkeys(entries))


def release_text(version, pull_requests, platforms="Windows and Android"):
    notes = []
    for pr in pull_requests:
        changes = implementations(pr.get("body", ""))
        if not changes:
            raise ValueError(f"PR #{pr.get('number')} has no feature-level release notes; publish stopped")
        notes.extend((pr.get("number"), label, body) for label, body in changes)
    if not notes:
        raise ValueError("The release has no documented implementation details")
    lines = [f"## What's New in Remindly {version}", "", f"Supported platforms: {platforms}.", "",
             "Each entry below comes from the reviewed pull request. Available features depend on the actual build platform.", ""]
    for pr, label, body in notes:
        lines.append(f"- **{label} (PR #{pr}):** {body}")
    lines.extend(["", "## Release verification and limitations", "",
                  "Check the linked pull requests and Issues for CI results, manual device verification, and known limitations."])
    return "\n".join(lines) + "\n"


def load_release_pulls(sha):
    """Use PR event metadata, or locate the merged PR for a main-branch release."""
    event_file = os.environ.get("GITHUB_EVENT_PATH")
    event = json.loads(Path(event_file).read_text()) if event_file else {}
    pull = event.get("pull_request")
    if pull:
        return [{"number": pull.get("number") or event.get("number"), "body": pull.get("body") or ""}]
    repo = os.environ["GITHUB_REPOSITORY"]
    shas = [sha]
    # The workflow may have published a version-metadata commit after the PR merge.
    shas.extend(subprocess.check_output(["git", "log", "-n", "15", "--format=%H"], text=True).splitlines())
    for commit in dict.fromkeys(shas):
        result = subprocess.run(["gh", "api", f"repos/{repo}/commits/{commit}/pulls"],
                                text=True, capture_output=True, check=False)
        if result.returncode != 0:
            continue
        pulls = json.loads(result.stdout)
        if pulls:
            return [{"number": p["number"], "body": p.get("body") or ""} for p in pulls
                    if p.get("merged_at")]
    raise ValueError("No merged PR description was found for release notes; publish stopped")
